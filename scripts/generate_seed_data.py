"""Generate docker/mysql-init/02_seed.sql: a deterministic synthetic retail dataset.

Dates are written relative to CURDATE() so "last 12 months" questions always
have data, however long ago the database was created. All data is fictional.

Run:  python scripts/generate_seed_data.py
"""

from __future__ import annotations

import random
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "docker" / "mysql-init" / "02_seed.sql"

REGIONS = ["North America", "Europe", "Asia Pacific", "Latin America"]
REGION_WEIGHTS = [38, 30, 22, 10]
SEGMENTS = ["Consumer", "Small Business", "Enterprise"]
CHANNELS = ["Online", "Retail Store", "Marketplace", "Phone"]
CHANNEL_WEIGHTS = [50, 25, 18, 7]
STATUSES = ["completed", "cancelled", "returned", "pending"]
STATUS_WEIGHTS = [86, 6, 5, 3]

# (name, category, unit_price, unit_cost)
PRODUCTS = [
    ("Trail Running Shoes", "Footwear", 89.90, 41.00),
    ("Leather Office Shoes", "Footwear", 124.00, 58.00),
    ("Canvas Sneakers", "Footwear", 54.50, 22.00),
    ("Waterproof Jacket", "Apparel", 139.00, 63.00),
    ("Merino Wool Sweater", "Apparel", 96.00, 44.00),
    ("Cotton T-Shirt 3-Pack", "Apparel", 29.90, 11.00),
    ("Slim Fit Jeans", "Apparel", 64.00, 26.50),
    ("Insulated Water Bottle", "Accessories", 24.50, 8.20),
    ("Canvas Backpack", "Accessories", 59.00, 24.00),
    ("Leather Wallet", "Accessories", 42.00, 15.50),
    ("Sunglasses Classic", "Accessories", 78.00, 21.00),
    ("Wireless Earbuds", "Electronics", 119.00, 62.00),
    ("Smart Fitness Watch", "Electronics", 189.00, 104.00),
    ("Portable Charger 20k", "Electronics", 39.90, 17.30),
    ("Bluetooth Speaker", "Electronics", 69.00, 33.00),
    ("Yoga Mat Pro", "Fitness", 45.00, 16.00),
    ("Adjustable Dumbbell Set", "Fitness", 159.00, 88.00),
    ("Resistance Bands Set", "Fitness", 22.90, 6.40),
    ("Ceramic Coffee Mug Set", "Home", 34.00, 12.50),
    ("Scented Candle Trio", "Home", 27.50, 8.90),
]

FIRST = ["Ava", "Liam", "Noah", "Mia", "Lucas", "Emma", "Ethan", "Sofia", "Mateo", "Aria", "Kai", "Nora", "Omar",
         "Priya", "Yuki", "Chen", "Elena", "Diego", "Hana", "Ivan", "Zara", "Tariq", "Lena", "Rafael", "Maya"]
LAST = ["Walker", "Rossi", "Tanaka", "Silva", "Novak", "Haddad", "Kim", "Mueller", "Garcia", "Patel", "Nguyen",
        "Johansson", "Okafor", "Dubois", "Santos", "Ivanov", "Cohen", "Moreau", "Lopez", "Bianchi"]

N_CUSTOMERS = 80
N_ORDERS = 1400
DAYS = 540  # about 18 months of history


def q(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def main() -> None:
    rng = random.Random(20260101)
    lines = [
        "-- GENERATED by scripts/generate_seed_data.py: do not edit by hand.",
        "-- Synthetic, fictional data. Dates are relative to CURDATE().",
        "",
        "SET NAMES utf8mb4;",
        "",
    ]

    customers = []
    names = set()
    while len(customers) < N_CUSTOMERS:
        name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        if name in names:
            continue
        names.add(name)
        customers.append((len(customers) + 1, name, rng.choices(REGIONS, REGION_WEIGHTS)[0], rng.choice(SEGMENTS)))
    lines.append("INSERT INTO customers (customer_id, customer_name, region, segment) VALUES")
    lines.append(",\n".join(f"({i}, {q(n)}, {q(r)}, {q(s)})" for i, n, r, s in customers) + ";")
    lines.append("")

    lines.append("INSERT INTO products (product_id, product_name, category, unit_price, unit_cost) VALUES")
    product_rows = [f"({i}, {q(n)}, {q(c)}, {p:.2f}, {k:.2f})" for i, (n, c, p, k) in enumerate(PRODUCTS, 1)]
    lines.append(",\n".join(product_rows) + ";")
    lines.append("")

    # Popularity weights give the data a believable long tail; a mild upward trend gives growth over time.
    popularity = [rng.choice([1, 2, 3, 5, 8]) for _ in PRODUCTS]
    orders, items = [], []
    item_id = 0
    for order_id in range(1, N_ORDERS + 1):
        days_ago = int(DAYS * (1 - rng.random() ** 0.8))
        customer_id = rng.choice(customers)[0]
        channel = rng.choices(CHANNELS, CHANNEL_WEIGHTS)[0]
        status = rng.choices(STATUSES, STATUS_WEIGHTS)[0]
        orders.append((order_id, customer_id, days_ago, channel, status))
        for product_id in rng.sample(range(1, len(PRODUCTS) + 1), rng.choice([1, 1, 2, 2, 3])):
            quantity = rng.choices([1, 2, 3, 4, 5], [55, 25, 10, 6, 4])[0]
            if rng.random() > popularity[product_id - 1] / 8:
                quantity = 1
            item_id += 1
            items.append((item_id, order_id, product_id, quantity))

    lines.append("INSERT INTO orders (order_id, customer_id, order_date, sales_channel, status) VALUES")
    lines.append(
        ",\n".join(
            f"({oid}, {cid}, DATE_SUB(CURDATE(), INTERVAL {d} DAY), {q(ch)}, {q(st)})" for oid, cid, d, ch, st in orders
        )
        + ";"
    )
    lines.append("")

    price = {i: p for i, (_, _, p, _) in enumerate(PRODUCTS, 1)}
    lines.append("INSERT INTO order_items (order_item_id, order_id, product_id, quantity, unit_price) VALUES")
    lines.append(",\n".join(f"({i}, {o}, {p}, {qty}, {price[p]:.2f})" for i, o, p, qty in items) + ";")
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(customers)} customers, {len(orders)} orders, {len(items)} order lines)")


if __name__ == "__main__":
    main()
